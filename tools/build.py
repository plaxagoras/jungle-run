"""Build hooks/frames.ts and art/preview.png from art/frames.txt.

Run: python3 -I tools/build.py   (needs Pillow for the preview)
The preview shows each frame twice: true pixels, and as the terminal will draw it
(octant cells, at most two colors per 2x4 cell, same reduction as hooks/art.ts).
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PALETTE = {
    # The explorer (tools/rig.py): our own design.
    'P': '#e9dfc0',  # bush hat
    'F': '#e8b48a',  # skin
    'G': '#b8875f',  # far arm
    'A': '#d9622b',  # shirt
    'M': '#7a4b26',  # pack
    'T': '#5a4426',  # trousers
    'Z': '#3e2e18',  # far leg
    'K': '#221a12',  # boots
    'S': '#e04848',  # the "!" alert, flames
    'W': '#f4f4f4',  # sparkle
    # The jungle (hooks/jungle.ts): flat bands in the hues of the 1982 jungle runners.
    'g': '#2f5a1a',  # canopy, crocodiles
    'h': '#69983f',  # jungle background
    't': '#4a4600',  # trunks, vines
    'y': '#bdb833',  # ground
    'd': '#807f1c',  # dirt band, log rings, quicksand
    'k': '#000000',  # tar pits, holes
    'r': '#6a6410',  # logs
    'w': '#2d6d97',  # pond water
    'o': '#eb9a3c',  # flame
    'H': '#f2e24a',  # gold
    'n': '#b8b8c0',  # silver
}
H = 32

def parse(text):
    frames, cur = {}, None
    for raw in text.splitlines():
        line = raw.rstrip()
        if line.startswith('#') or not line:
            continue
        if line.startswith('= '):
            parts = line[2:].split()
            cur = parts[0]
            if len(parts) == 4 and parts[1] == '<':
                src, k = frames[parts[2]], int(parts[3][3:])
                g = src
                for _ in range(k):
                    g = [''.join(g[len(g) - 1 - r][c] for r in range(len(g))) for c in range(len(g[0]))]
                frames[cur] = g
                cur = None
            else:
                frames[cur] = []
            continue
        bad = set(line) - set(PALETTE) - {'.'}
        if bad:
            sys.exit(f'{cur}: unknown pixel letters {bad}')
        frames[cur].append(line)
    out = {}
    for name, rows in frames.items():
        w = max(16, max(len(r) for r in rows))
        rows = [r.ljust(w, '.') for r in rows]
        if len(rows) > H:
            sys.exit(f'{name}: {len(rows)} rows > {H}')
        out[name] = ['.' * w] * (H - len(rows)) + rows
    return out

def cells(rows):
    """Same reduction as hooks/art.ts octantCells: per 2x4 cell, (mask, fg, bg)."""
    res = []
    for y in range(0, H, 4):
        line = []
        for x in range(0, len(rows[0]), 2):
            px = [rows[y + dy][x + dx] if x + dx < len(rows[0]) else '.' for dy in range(4) for dx in range(2)]
            counts = {}
            for p in px:
                counts[p] = counts.get(p, 0) + 1
            ranked = sorted(counts, key=lambda c: -counts[c])
            if ranked == ['.']:
                line.append((0, None, None)); continue
            fg = next(c for c in ranked if c != '.')
            other = next((c for c in ranked if c != fg), None)
            bg = other if other and other != '.' and '.' not in ranked else None
            mask = 0
            for i, p in enumerate(px):
                if p == fg or (p != '.' and p != bg and not bg):
                    mask |= 1 << i
            line.append((mask, fg, bg))
        res.append(line)
    return res

def preview(frames):
    from PIL import Image, ImageDraw
    S, gap = 6, 12
    names = list(frames)
    width = sum(len(frames[n][0]) * S + gap for n in names) + gap
    img = Image.new('RGB', (width, (H * S + gap) * 2 + gap + 14), '#000000')
    d = ImageDraw.Draw(img)
    x0 = gap
    for n in names:
        rows = frames[n]
        d.text((x0, 2), n, fill='#888888')
        for y, r in enumerate(rows):
            for x, p in enumerate(r):
                if p != '.':
                    d.rectangle([x0 + x * S, 14 + y * S, x0 + x * S + S - 1, 14 + y * S + S - 1], fill=PALETTE[p])
        top = 14 + H * S + gap
        for cy, line in enumerate(cells(rows)):
            for cx, (mask, fg, bg) in enumerate(line):
                for i in range(8):
                    on = mask >> i & 1
                    col = PALETTE[fg] if on and fg else (PALETTE[bg] if bg else None)
                    if col:
                        px, py = cx * 2 + i % 2, cy * 4 + i // 2
                        d.rectangle([x0 + px * S, top + py * S, x0 + px * S + S - 1, top + py * S + S - 1], fill=col)
        x0 += len(rows[0]) * S + gap
    img.save(ROOT / 'art' / 'preview.png')

def main():
    frames = parse((ROOT / 'art' / 'frames.txt').read_text())
    ts = ['// Generated by tools/build.py from art/frames.txt. Edit the .txt, then rebuild.',
          f'export const PALETTE: Record<string, string> = {json.dumps(PALETTE)}',
          'export const FRAMES = {']
    for n, rows in frames.items():
        ts.append(f'  {n}: {json.dumps(rows)},')
    ts.append('} as const satisfies Record<string, readonly string[]>')
    ts.append('export type FrameName = keyof typeof FRAMES')
    (ROOT / 'hooks' / 'frames.ts').write_text('\n'.join(ts) + '\n')
    try:
        preview(frames)
    except ImportError:
        print('no Pillow: skipped preview')
    print(f'{len(frames)} frames:', ', '.join(f'{n} {len(r[0])}x{len(r)}' for n, r in frames.items()))

if __name__ == "__main__":
    main()
